s32 dbgMenuFloorChange(s32 id) {
    s32 param = 0;
    s32 i;

    if ((GSinputButtonsPressed(1) & 0x20) && menuSubOpenNumberInputDigit(0, &param) == 0) {
        return -1;
    }
    for (i = 0; i < 0xF7; i++) {
        if (id == floor_change_tbl[i].from) {
            if ((GSinputButtonsPressed(1) & 0x40) || (GSinputButtonsPressed(1) & 0x800)) {
                floorDataBiosGetPtr(floor_change_tbl[i].to);
                floorDataBiosGetGroupID();
                GSfsysFreeCache();
            }
            floorLink(floor_change_tbl[i].to, param);
            break;
        }
    }
    return 0;
}

s32 dbgMenuFloorCheck(void) {
    s32 param;
    s32 i;

    if (GSfloorIsFloorPushed()) {
        GSsndPlayNow(0x13);
        i = 0;
        do {
            GSprint(dbgMenuGetLayerID(), 0xC8, 0xF0, -1, "\x82\xB1\x82\xCC\x83\x74\x83\x8D\x83\x41\x82\xA9\x82\xE7\x83\x74\x83\x8D\x83\x41\x83\x60\x83\x46\x83\x93\x83\x57\x82\xCD\x82\xA8\x82\xB1\x82\xC8\x82\xA6\x82\xDC\x82\xB9\x82\xF1");
            GSthreadSwitch();
            i++;
        } while (i < 0xF);
        return 0;
    }
    if ((GSinputButtonsPressed(1) & 0x20) || (GSinputButtonsPressed(1) & 0x800)) {
        if (menuSubOpenNumberInputDigit(0, &param) == 0) {
            return -1;
        }
        floorLink(param, 0);
        return 0;
    }
    return 1;
}
